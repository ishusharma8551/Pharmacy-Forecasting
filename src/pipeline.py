def demand_stats(sales, forecasts):
    """Per-medicine demand statistics used by risk scoring and inventory formulas."""
    last = sales["Date"].max()
    recent28 = sales[sales["Date"] > last - pd.Timedelta(days=28)].groupby("Medicine_ID")["Units_Sold"].mean()
    sigma90 = sales[sales["Date"] > last - pd.Timedelta(days=90)].groupby("Medicine_ID")["Units_Sold"].std()
    s = pd.DataFrame({"Avg_Daily_28": recent28, "Sigma_Daily": sigma90.fillna(0.0)}).reset_index()
    return forecasts.merge(s, on="Medicine_ID", how="left")


def analyze_inventory(medicines, batches, stats, expiry_bundle, as_of):
    scored = exp.score_batches(batches, medicines, stats, expiry_bundle, as_of)
    recs = inv.medicine_recommendations(medicines, scored, stats)
    fefo = inv.fefo_table(scored)
    return scored, recs, fefo


def _block(df):
    return "```\n" + df.to_string(index=False) + "\n```"


def write_results_summary(demand_metrics, expiry_metrics, cleaning_report):
    d = demand_metrics[demand_metrics.Split == "test"].sort_values(["Horizon", "MAE"])
    e = expiry_metrics[expiry_metrics.Split == "test"]
    lines = ["# Results summary (auto-generated by `python train.py`)", "",
             f"> {config.DATA_DISCLAIMER}", "",
             "These numbers come from running the code on **synthetic** data. They show that the pipeline "
             "works end to end; they are **not** evidence of real-world accuracy.", "",
             "## Data cleaning", "",
             f"- Rows in raw sales file: {cleaning_report['rows_in']:,}",
             f"- Duplicates removed: {cleaning_report['duplicates_removed']}",
             f"- Missing values interpolated: {cleaning_report['missing_filled']}",
             f"- Outliers capped: {cleaning_report['outliers_capped']}", "",
             "## Demand forecasting (test set, chronological hold-out)", "",
             _block(d[["Horizon", "Model", "Type", "MAE", "RMSE", "MAPE_%", "WAPE_%", "Selected"]].round(2)), "",
             "`Selected` marks the ML model chosen on the VALIDATION period (not on test).", "",
             "## Expiry-risk classification (test set)", "",
             _block(e[["Model", "Accuracy", "Precision_macro", "Recall_macro", "F1_macro", "Recall_High",
                       "Selected"]].round(3)), ""]
    (config.REPORTS_DIR / "results_summary.md").write_text("\n".join(lines), encoding="utf-8")


def save_everything_to_db(out):
    db.init_db(reset=True)
    db.save_table("medicines", out["medicines"])
    db.save_table("batches", out["batches"])
    db.save_table("sales_daily", out["sales"].assign(Units_Sold=out["sales"]["Units_Sold"].astype(float)))
    db.save_table("forecasts", out["forecasts"])
    db.save_table("forecast_test", out["test_predictions"])
    db.save_table("expiry_predictions", out["scored"])
    db.save_table("recommendations", out["recs"])
    db.save_table("fefo", out["fefo"])
    db.save_table("meta", pd.DataFrame({"key": ["as_of", "data_disclaimer", "trained_through"],
                                        "value": [str(out["as_of"].date()), config.DATA_DISCLAIMER,
                                                  out["demand_bundle"]["trained_through"]]}))


def run_pipeline(quick=False, regenerate=True, verbose=True, n_medicines=None, history_days=None):
    t0 = time.time()
    log = print if verbose else (lambda *a, **k: None)
    n_dem, n_exp, n_snap = (30, 40, 12) if quick else (100, 150, config.SNAPSHOTS_PER_MEDICINE)
    config.MODELS_DIR.mkdir(parents=True, exist_ok=True)
    config.REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    config.PROCESSED_DIR.mkdir(parents=True, exist_ok=True)

    log("[1/7] Generating SYNTHETIC raw data" if regenerate else "[1/7] Using existing raw data")
    if regenerate or not (config.RAW_DIR / "sales_daily.csv").exists():
        from data.generate_data import write_raw_files
        write_raw_files(n_medicines=n_medicines, history_days=history_days)

    log("[2/7] Validating and cleaning")
    clean = pp.run_cleaning()
    for sev, msg in clean["issues"]:
        log(f"   {sev.upper():7s} {msg}")
    log(f"   cleaning report: {clean['report']}")
    medicines, batches, sales = clean["medicines"], clean["batches"], clean["sales"]
    as_of = sales["Date"].max()

    log("[3/7] Exploratory data analysis (figures -> reports/figures)")
    eda.run_eda(sales, medicines, batches, as_of)

    log("[4/7] Demand forecasting: baselines + Linear Regression / Random Forest / XGBoost")
    dem = dfc.train_demand_models(sales, medicines, n_estimators=n_dem, verbose=verbose)
    forecasts = dfc.forecast_latest(dem["bundle"], sales, medicines)

    log("[5/7] Expiry-risk classification")
    snaps, cat_map = exp.build_snapshots(sales, medicines, dem["features"], n_per_med=n_snap, n_estimators=40 if quick else 60)
    ex = exp.train_expiry_models(snaps, cat_map, n_estimators=n_exp, verbose=verbose)

    log("[6/7] Inventory optimisation (ROP, safety stock, FEFO)")
    stats = demand_stats(sales, forecasts)
    scored, recs, fefo = analyze_inventory(medicines, batches, stats, ex["bundle"], as_of)
    scored.to_csv(config.REPORTS_DIR / "expiry_predictions.csv", index=False)
    recs.to_csv(config.REPORTS_DIR / "inventory_recommendations.csv", index=False)
    fefo.to_csv(config.REPORTS_DIR / "fefo_recommendations.csv", index=False)
    log(f"   recommendations: {recs['Recommendation'].value_counts().to_dict()}")

    log("[7/7] Saving to SQLite")
    out = {"medicines": medicines, "batches": batches, "sales": sales, "forecasts": forecasts,
           "test_predictions": dem["test_predictions"], "scored": scored, "recs": recs, "fefo": fefo,
           "as_of": as_of, "demand_bundle": dem["bundle"]}
    save_everything_to_db(out)
    write_results_summary(dem["metrics"], ex["metrics"], clean["report"])
    log(f"Done in {time.time() - t0:.0f}s. Database: {config.DB_PATH}")
    return out


# ------------------------------------------------ refresh / upload helpers
def load_expiry_bundle():
    return joblib.load(config.MODELS_DIR / "expiry_model.pkl")


def refresh_recommendations():
    """Re-score the CURRENT database contents (after CRUD edits) and rewrite derived tables."""
    medicines, batches = db.read_table("medicines"), db.read_table("batches")
    forecasts, sales = db.read_table("forecasts"), db.read_table("sales_daily")
    as_of = pd.Timestamp(db.read_table("meta").set_index("key").loc["as_of", "value"])
    stats = demand_stats(sales, forecasts)
    scored, recs, fefo = analyze_inventory(medicines, batches, stats, load_expiry_bundle(), as_of)
    db.save_table("expiry_predictions", scored)
    db.save_table("recommendations", recs)
    db.save_table("fefo", fefo)
    return scored, recs, fefo


def analyze_uploaded(flat, as_of=None):
    """Score an uploaded flat inventory CSV (already validated).

    Demand estimate = Daily_Sales column (no sales history is uploaded). Variability is assumed to be
    35% of daily sales (ASSUMPTION). If a Medicine_ID exists in the database, its ML forecast is used.
    """
    medicines, batches = pp.split_flat_inventory(flat)
    daily = flat.groupby("Medicine_ID")["Daily_Sales"].first().astype(float)
    stats = pd.DataFrame({"Medicine_ID": daily.index, "Forecast_7d": daily.values * 7,
                          "Forecast_15d": daily.values * 15, "Forecast_30d": daily.values * 30,
                          "Avg_Daily_28": daily.values, "Sigma_Daily": daily.values * 0.35})
    if db.table_exists("forecasts"):
        known = db.read_table("forecasts")
        sales = db.read_table("sales_daily")
        known_stats = demand_stats(sales, known)
        stats = pd.concat([known_stats[known_stats["Medicine_ID"].isin(stats["Medicine_ID"])],
                           stats[~stats["Medicine_ID"].isin(known_stats["Medicine_ID"])]], ignore_index=True)
    if as_of is None:
        as_of = pd.Timestamp(db.read_table("meta").set_index("key").loc["as_of", "value"]) if db.table_exists("meta") \
            else pd.Timestamp.today().normalize()
    return analyze_inventory(medicines, batches, stats, load_expiry_bundle(), as_of)
